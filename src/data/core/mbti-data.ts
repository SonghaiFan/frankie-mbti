const stackOf = new Map(mbtiTypes.map((t) => [t.type, t.cognitiveFunctions.split(" ")]));
const flip = (f: string) => f[0] + (f[1] === "i" ? "e" : "i");

/** The eight Beebe slots of a type: its stack, then the same functions with the attitude flipped. */
export const beebeStackOf = (code: string) => {
  const top = stackOf.get(code) ?? [];
  return [...top, ...top.map(flip)];
};

/** How pair[0]'s stack sits against pair[1]'s. */
export function relationOf(a: string, b: string): PairRelation {
  const eight = beebeStackOf(b);
  const signature = (stackOf.get(a) ?? []).map((f) => eight.indexOf(f) + 1).join("");
  const found = pairRelations.find((r) => r.signature === signature);
  if (!found) throw new Error(`no pair relation for ${a} × ${b}`);
  return found;
}

